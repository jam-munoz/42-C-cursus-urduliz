#include "libft.h"

void	ft_putendl_fd(char *s, int fd)
{
	char	buf[1024];
	int		i;

	i = 0;
	while (s[i] != '\0' && i < 1022)
	{
		buf[i] = s[i];
		i++;
	}
	buf[i] = '\n';
	write(fd, buf, i + 1);
}
