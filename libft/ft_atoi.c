int	ft_atoi(const char *nptr)
{
	int	i;
	int	sign;
	int	sum;

	if (!nptr)
		return (0);
	i = 0;
	sign = 1;
	sum = 0;
	while (nptr[i] == ' ' || (9 <= nptr[i] && nptr[i] <= 13))
		i++;
	if (nptr[i] == '+' || nptr[i] == '-')
	{
		if (nptr[i] == '-')
			sign = -1;
		i++;
	}
	while ('0' <= nptr[i] && nptr[i] <= '9')
	{
		sum *= 10;
		sum += nptr[i] - '0';
		i++;
	}
	return (sum * sign);
}
